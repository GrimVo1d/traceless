package jpeg

// maxCodeLen is the longest Huffman code JPEG allows.
const maxCodeLen = 16

// huffSpec is a Huffman table as stored in a DHT segment: the number of codes
// of each length from 1 to 16, then the symbols in code order.
type huffSpec struct {
	counts  [maxCodeLen]byte
	symbols []byte
}

// decoder decodes one Huffman table with the canonical code procedure of
// ITU T.81 F.2.2.3: codes of one length are consecutive integers.
type decoder struct {
	maxCode [maxCodeLen + 1]int32 // largest code of each length, -1 if none
	valPtr  [maxCodeLen + 1]int32 // index of the first symbol of each length minus its code
	symbols []byte
}

// newDecoder builds a decoder, rejecting tables whose codes don't fit in their
// lengths. A decoder can't reach codes past that point.
func newDecoder(s huffSpec) (*decoder, error) {
	d := &decoder{symbols: s.symbols}
	code, k := int32(0), int32(0)
	for l := 1; l <= maxCodeLen; l++ {
		n := int32(s.counts[l-1])
		d.maxCode[l] = -1
		if n > 0 {
			d.valPtr[l] = k - code
			code += n
			k += n
			d.maxCode[l] = code - 1
		}
		// Like libjpeg, reject the all-ones code too: it is reserved.
		if code >= 1<<l {
			return nil, malformed("Huffman table has too many codes of length %d", l)
		}
		code <<= 1
	}
	return d, nil
}

// encoder maps symbols to codes for the standard tables.
type encoder struct {
	code [256]uint16
	size [256]uint8 // 0 if the symbol has no code
}

func newEncoder(s huffSpec) *encoder {
	e := &encoder{}
	code, k := uint16(0), 0
	for l := 1; l <= maxCodeLen; l++ {
		for range s.counts[l-1] {
			sym := s.symbols[k]
			e.code[sym], e.size[sym] = code, uint8(l)
			code++
			k++
		}
		code <<= 1
	}
	return e
}

