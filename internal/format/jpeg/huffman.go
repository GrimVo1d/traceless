// appendDHT appends a DHT segment body defining table class tc, number th.
func appendDHT(b []byte, tc, th byte, s huffSpec) []byte {
	b = append(b, tc<<4|th)
	b = append(b, s.counts[:]...)
	return append(b, s.symbols...)
}
